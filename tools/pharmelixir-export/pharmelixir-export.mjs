#!/usr/bin/env node
// pharmelixir-export — turn one PharmElixir campaign into a folder that `sdd.mjs push` can send to Studio.
//
//   node pharmelixir-export.mjs --data <PharmElixir/webapp/data.js> --campaign phgdh-npa --out <folder>
//        [--label r018-import] [--campaign-db <data/campaign_db/phgdh-npa.sqlite3>]
//        [--pharmelixir http://127.0.0.1:8056] [--studio https://studio.smartdrugdiscovery.org]
//
// Reads the data layer that PharmElixir's build_pharmelixir_data.py generates (window.PX_DATA) and writes
//   <out>/sdd.project.json
//   <out>/Results/<label>/iteration.md
//   <out>/Results/<label>/tables/*.csv     compounds, rounds, tiers, secondary targets, scorecard, ...
// Optional: the campaign's SQLite file adds the synthesis shortlist and confirmed flags (Node 22.5+), and a
// running PharmElixir server adds the decision sheet and connectivity matrix exactly as the app computes them.
//
// data.js is JavaScript generated by your own PharmElixir build and is executed to read PX_DATA. node:vm keeps
// it away from this script's variables but is NOT a security boundary: only run this on files from your own build.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import vm from "node:vm";

function die(msg) {
  console.error(`pharmelixir-export: ${msg}`);
  process.exit(1);
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (!argv[i].startsWith("--")) continue;
    const k = argv[i].slice(2), v = argv[i + 1];
    if (v === undefined || v.startsWith("--")) out[k] = true;
    else { out[k] = v; i++; }
  }
  return out;
}

const args = parseArgs(process.argv.slice(2));
for (const k of ["data", "campaign", "out"]) if (typeof args[k] !== "string") die(`--${k} is required`);
const campaign = args.campaign;
if (!/^[a-z0-9][a-z0-9-]{0,47}$/.test(campaign)) die("--campaign must be a lowercase slug, e.g. phgdh-npa");

// ── load PX_DATA ──────────────────────────────────────────────────────────────
const ctx = vm.createContext({ window: {}, console: { log() {}, warn() {}, info() {} } });
vm.runInContext(readFileSync(args.data, "utf8"), ctx, { timeout: 30000 });
const PX = ctx.window.PX_DATA;
if (!PX?.campaignData?.[campaign]) die(`campaign "${campaign}" is not in ${args.data}; it has ${Object.keys(PX?.campaignData ?? {}).join(", ")}`);
const C = PX.campaignData[campaign];
const round = C.live?.round ?? C.round ?? (C.liveRounds?.length ? C.liveRounds[C.liveRounds.length - 1].round : null);
const label = typeof args.label === "string" ? args.label : `r${String(round ?? 0).padStart(3, "0")}-pharmelixir`;

// ── helpers ───────────────────────────────────────────────────────────────────
const snake = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").toLowerCase();
const scalar = (v) => (v == null || v === "" ? null : typeof v === "number" || typeof v === "boolean" ? v : String(v));
const listText = (a) => (Array.isArray(a) ? a.map((x) => (x && typeof x === "object" ? x.gene ?? x.id ?? x.name ?? JSON.stringify(x) : x)).join("; ") : scalar(a));

function csv(rows) {
  if (!rows.length) return "";
  const cols = [];
  for (const r of rows) for (const k of Object.keys(r)) if (!cols.includes(k)) cols.push(k);
  const esc = (v) => (v == null ? "" : /[",\n\r]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
  return [cols.join(","), ...rows.map((r) => cols.map((c) => esc(r[c])).join(","))].join("\n") + "\n";
}

/** One compound record → one flat row: nested objects become prefix_key, lists become "a; b". */
function flattenCompound(c) {
  const row = {};
  for (const [k, v] of Object.entries(c)) {
    if (v == null) { row[snake(k)] = null; continue; }
    if (k === "breakdown" && Array.isArray(v)) {
      for (const b of v) if (b?.id) row[`score_${snake(b.id)}`] = scalar(b.contribution);
    } else if (k === "tier" && typeof v === "object") {
      row.tier_reached = scalar(v.reached); row.tier_status = scalar(v.status); row.tier_label = scalar(v.label); row.tier_pending_at = scalar(v.pendingAt);
    } else if (Array.isArray(v)) {
      row[snake(k)] = listText(v) || null;
    } else if (typeof v === "object") {
      for (const [kk, vv] of Object.entries(v)) if (vv == null || typeof vv !== "object") row[`${snake(k)}_${snake(kk)}`] = scalar(vv);
    } else {
      row[snake(k)] = scalar(v);
    }
  }
  return row;
}

const tables = {};
const put = (name, rows) => { if (rows && rows.length) tables[name] = rows; };

put("compounds", (C.compounds ?? []).map(flattenCompound));
put("rounds", (C.rounds?.length ? C.rounds : C.liveRounds ?? []).map((r) => Object.fromEntries(Object.entries(r).map(([k, v]) => [snake(k), scalar(v)]))));
if (C.rounds?.length && C.liveRounds?.length) put("round_counts", C.liveRounds.map((r) => Object.fromEntries(Object.entries(r).map(([k, v]) => [snake(k), scalar(v)]))));
if (C.tiers?.length) {
  const counts = new Map((C.funnelCounts ?? []).map((f) => [f.n, f]));
  put("tiers", C.tiers.map((t) => ({
    tier: t.n, name: scalar(t.name), short: scalar(t.short), method: scalar(t.method), gate: scalar(t.gate), threshold: scalar(t.thr),
    validation: scalar(t.validation), validation_tool: scalar(t.validationTool), compounds_in: scalar(counts.get(t.n)?.in), compounds_passed: scalar(counts.get(t.n)?.pass),
  })));
}
put("secondary_targets", (C.secondaryTargets ?? []).map((s) => ({
  gene: scalar(s.gene), category: scalar(s.category), n_compounds: scalar(s.nCompounds), mean_prob: scalar(s.meanProb),
  max_prob: scalar(s.maxProb), breadth: scalar(s.breadth), compounds: listText(typeof s.compounds === "string" ? s.compounds.split(";").map((x) => x.trim()) : s.compounds),
})));
put("scorecard", (C.scorecard ?? []).map((s) => ({ measure: scalar(s.label), direction: scalar(s.dir), rule: scalar(s.rule), value: scalar(s.value), status: scalar(s.status) })));
const live = C.live ?? {};
put("summary", Object.keys(live).length ? [Object.fromEntries(Object.entries(live).map(([k, v]) => [snake(k), scalar(v)]))] : []);

// ── optional: campaign SQLite (synthesis shortlist, confirmed flags) ──────────
if (typeof args["campaign-db"] === "string") {
  let DatabaseSync;
  try { ({ DatabaseSync } = await import("node:sqlite")); } catch { die("--campaign-db needs Node 22.5 or later (node:sqlite)."); }
  const db = new DatabaseSync(args["campaign-db"], { readOnly: true });
  const has = (t) => !!db.prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?").get(t);
  if (has("synthesis")) {
    put("synthesis_shortlist", db.prepare("SELECT compound_id, payload, saved_at FROM synthesis").all().map((r) => {
      let p = {};
      try { p = JSON.parse(r.payload); } catch { /* keep the id */ }
      return { compound_id: r.compound_id, name: scalar(p.name), smiles: scalar(p.smiles), score: scalar(p.score), tier: scalar(p.tier), saved_at: scalar(r.saved_at) };
    }));
  }
  if (has("dm_flags")) put("confirmed_flags", db.prepare("SELECT compound_id, flag, rationale, decided_by, updated_at FROM dm_flags").all().map((r) => ({ ...r })));
  db.close();
}

// ── optional: a running PharmElixir server (decision sheet, connectivity) ─────
if (typeof args.pharmelixir === "string") {
  const base = args.pharmelixir.replace(/\/+$/, "");
  const get = async (p) => { const r = await fetch(base + p); return r.ok ? r.json() : null; };
  const dm = await get(`/api/npa/decision_matrix?campaign=${campaign}`).catch(() => null);
  if (dm?.rows?.length) {
    put("decision_sheet", dm.rows.map((r) => {
      const row = {
        compound_id: scalar(r.compound_id), lineage: scalar(r.lineage_id), flag: scalar(r.flag || r.auto_decision), auto_decision: scalar(r.auto_decision),
        flag_by: scalar(r.flag_by), action: scalar(r.action), candidacy: scalar(r.candidacy), good_binders: scalar(r.good_binders), anti_binders: scalar(r.anti_binders),
        novelty: scalar(r.novelty_flag), panel_points: scalar(r.panel_points), panel_rank: scalar(r.panel_rank), pubchem_cid: scalar(r.pubchem_cid),
        cleared: scalar(r.cleared), rationale: scalar(r.rationale), smiles: scalar(r.smiles),
      };
      if (r.values && typeof r.values === "object") for (const [k, v] of Object.entries(r.values)) row[`criterion_${snake(k)}`] = scalar(v);
      return row;
    }));
    if (dm.rule) tables.__rule = dm.rule;
  }
  const cn = await get(`/api/npa/connectivity?campaign=${campaign}`).catch(() => null);
  if (cn?.genes?.length && cn?.drugs?.length) {
    const rows = [];
    cn.drugs.forEach((d, i) => cn.genes.forEach((g, j) => {
      const v = cn.cells?.[i]?.[j];
      if (v) rows.push({ compound_id: d, gene: g, engagement: scalar(v), primary: g === cn.primaryGene, anti_target: (cn.antiGenes ?? []).includes(g) });
    }));
    put("connectivity", rows);
  }
}

// ── write ─────────────────────────────────────────────────────────────────────
const rule = tables.__rule; delete tables.__rule;
const dir = join(args.out, "Results", label);
mkdirSync(join(dir, "tables"), { recursive: true });
for (const [name, rows] of Object.entries(tables)) writeFileSync(join(dir, "tables", `${name}.csv`), csv(rows));

const lines = [
  `# ${label}`,
  "",
  `- Project: ${campaign}`,
  `- Exported: ${new Date().toISOString().slice(0, 10)} from PharmElixir's data layer (build_pharmelixir_data.py)${typeof args.pharmelixir === "string" ? " and its server" : ""}`,
  `- Source master database: ${live.source ?? "see PharmElixir"}`,
  `- Status: draft (not released)`,
  "",
  "## Contents",
  ...Object.entries(tables).map(([n, r]) => `- \`tables/${n}.csv\`: ${r.length} rows`),
  "",
  "## Notes",
  "- All scores, docking values (pred_*), ADMET and toxicity probabilities (hs_*) are in-silico results, not experimental measurements. pred_* values are docking-derived surrogates, not measured affinity.",
  rule ? `- Decision rule: ${rule}` : null,
  `- Current round: ${round ?? "—"}; pool ${live.pool ?? "—"}; gate-clean ${live.gateClean ?? "—"}.`,
].filter((l) => l !== null);
writeFileSync(join(dir, "iteration.md"), lines.join("\n") + "\n");

const cfg = {
  project: campaign,
  studio: typeof args.studio === "string" ? args.studio : "https://studio.smartdrugdiscovery.org",
  include: ["Results/**"],
  exclude: [],
  sensitivity: "unpublished",
  tables: Object.fromEntries(Object.keys(tables).map((n) => [`Results/*/tables/${n}.csv`, n])),
};
writeFileSync(join(args.out, "sdd.project.json"), JSON.stringify(cfg, null, 2) + "\n");

console.log(`Wrote ${args.out} for ${campaign}, iteration ${label}:`);
for (const [n, r] of Object.entries(tables)) console.log(`  ${n.padEnd(20)} ${String(r.length).padStart(6)} rows`);
console.log(`Next: cd ${args.out} && node sdd.mjs push --label ${label} --token-file <push key file>`);
